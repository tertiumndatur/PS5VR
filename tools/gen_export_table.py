#!/usr/bin/env python3
"""Emit C tables of {name, offset} for chosen exports of decrypted system
libraries, for apps that cannot sceKernelDlsym them, plus one anchor string per
library (its address and text in the read-only data segment).

System library code is mapped execute-only, so the app checks the anchor string
instead: the offsets are used only if the string sits at the same offset, i.e.
it is the same library build, so other firmware fails safely.

usage: gen_export_table.py [--suffix 720] [--names reference.h]
       <lib.sprx> <name>... [-- <lib.sprx> <name>...] > table.h
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import ps5_dynlib  # noqa: E402


def anchor(prx):
    """First printable C string of 12+ chars in the read-only LOAD segment."""
    seg = next((p for p in prx.loads if p["flags"] == 4), None)
    if seg is None:
        raise ValueError(f"{prx.path.name}: no read-only LOAD segment")
    data = prx.data[seg["offset"]:seg["offset"] + seg["filesz"]]
    m = re.search(rb"[A-Za-z][A-Za-z0-9 _%:.,()-]{11,59}\x00", data)
    if m is None:
        raise ValueError(f"{prx.path.name}: no suitable anchor string")
    text = m.group(0)[:-1].decode().replace("\\", "\\\\").replace('"', '\\"')
    return seg["vaddr"] + m.start(), text


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--suffix", default="", help="suffix for generated C identifiers (e.g. 720)")
    ap.add_argument("--names", action="append", type=Path, default=[],
                    help="extra candidate-name file/dir (e.g. an existing export table)")
    ap.add_argument("groups", nargs=argparse.REMAINDER, help="libraries and export names, split by --")
    args = ap.parse_args()
    if args.suffix and not re.fullmatch(r"[A-Za-z0-9_]+", args.suffix):
        ap.error("--suffix must contain only letters, digits and underscores")
    groups, cur = [], []
    for arg in args.groups:
        if arg == "--":
            groups.append(cur)
            cur = []
        else:
            cur.append(arg)
    groups.append(cur)
    if any(len(group) < 2 for group in groups):
        ap.error("each group needs a library and at least one export name")

    names = ps5_dynlib.NameDB()
    names.load_persistent()
    for extra in args.names:
        names.add_path(extra)
    lines = ["/* Generated by ps5vr/tools/gen_export_table.py - do not edit. */"]
    for group in groups:
        lib, wanted = Path(group[0]), group[1:]
        prx = ps5_dynlib.Prx(lib)
        names.add_blob(prx.data)
        prx.resolve(names)
        by_name = {s["name"]: s for s in prx.exports() if s["name"]}
        stem = lib.name.split(".")[0]
        lines.append(f"static const export_sig_t k{stem}Exports{args.suffix}[] = {{")
        for name in wanted:
            s = by_name.get(name)
            if s is None:
                sys.exit(f"{lib.name}: no export named {name}")
            if s["type"] != "FUNC" or not any(
                    p["flags"] & ps5_dynlib.PF_X and
                    p["vaddr"] <= s["value"] < p["vaddr"] + p["filesz"]
                    for p in prx.loads):
                sys.exit(f"{lib.name}: {name} is not a function in an executable segment")
            lines.append(f'  {{"{name}", 0x{s["value"]:x}}},')
        lines.append("};")
        va, text = anchor(prx)
        lines.append(f'static const export_anchor_t k{stem}Anchor{args.suffix} = {{0x{va:x}, "{text}"}};')
    print("\n".join(lines))


if __name__ == "__main__":
    main()
